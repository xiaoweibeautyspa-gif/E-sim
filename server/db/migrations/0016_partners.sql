--
-- Partners, affiliates, B2B agents and corporate accounts (Phase 9).
--
-- WHY THIS MIGRATION EXISTS
-- -------------------------
-- `server/routes/affiliates.ts`, `partners.ts`, `b2b.ts`, `corporate.ts` and
-- `redirect.affiliate.ts` (already saved in this milestone) all read/write a
-- set of tables that do not exist yet. This migration creates them so the
-- routes stop failing-safe and the dashboards show real data.
--
-- WHAT IT COVERS (mapped to the phase acceptance criteria)
-- -------------------------------------------------------
--   • Affiliate program: signup, unique link code, 30-day cookie window,
--     commission %, dashboard with clicks / sales / payouts owed.
--       → affiliate_accounts, affiliate_clicks, affiliate_conversions,
--         affiliate_payouts
--   • Partner QR program: printable standee → EN/ZH/VI landing, commission,
--     partner dashboard. Partner is a distinct entity from an affiliate
--     (it's a physical venue; it earns commission on QR-redirected sales).
--       → partner_accounts, partner_clicks, partner_conversions,
--         partner_payouts
--   • B2B agent portal: application form, tier pricing, bulk order, send
--     to clients.
--       → b2b_agents, b2b_agent_applications, b2b_tier_pricing
--   • Corporate accounts: company admin buys + assigns eSIMs to staff,
--     sees usage, monthly invoicing.
--       → corporate_accounts, corporate_members, corporate_assignments,
--         corporate_invoices
--
-- DESIGN NOTES
-- ------------
--  • All public "handle" columns are unique + text (not numeric ids) so URLs
--    like /r/<code> and /partner/<slug> are unguessable and shareable.
--  • Money columns are stored in the row's currency as NUMERIC(12, 2). VND is
--    zero-decimal upstream but 2dp storage is harmless and keeps every
--    currency in the same column shape; conversion to display units happens
--    in the service layer.
--  • `commission_percent` is NUMERIC(5, 2) with a 0..100 CHECK, matching the
--    `%` semantics in affiliate/partner dashboards.
--  • `attribution_window_days` defaults to 30 for affiliates per the spec;
--    partner rows use the same default because the QR-redirect cookie has
--    the same shape.
--  • Soft FKs: user_id / order_id / esim_id point at tables owned by earlier
--    migrations. We DO NOT add an FK constraint because the ordering of the
--    referenced tables across migrations is fragile and the app already
--    treats these as soft joins (see 0011_trips.sql for the same pattern).
--    Columns are indexed so joins stay fast.
--  • Every table is `IF NOT EXISTS` and every seed uses `ON CONFLICT DO
--    NOTHING` so the file is idempotent and safe to re-run.
--  • No real affiliate IDs, commissions, or partner identities are seeded.
--    Settings-style defaults live in `partner_settings` so the admin UI can
--    edit them (commission %, cookie window, tier pricing).
--
-- Run after 0015_emails_alerts.sql.

BEGIN;

-- ===========================================================================
-- AFFILIATES
-- ===========================================================================

-- An affiliate = a travel blogger (or anyone) who signs up and gets a unique
-- link. Trust model: signup is self-service; payouts are reviewed in admin.
CREATE TABLE IF NOT EXISTS affiliate_accounts (
  id                       integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- Stable public handle used in URLs (`/r/<public_code>`). Never reuse a
  -- code, even after deactivation, so old links keep resolving to the same
  -- affiliate account.
  public_code              text         NOT NULL,

  -- Linkage to users.id (soft) — NULL for affiliates who have not signed up
  -- an account yet (e.g. seeded by an admin for a manual partner).
  user_id                  integer      NULL,

  email                    text         NOT NULL,
  display_name             text         NOT NULL,
  website                  text         NULL,

  -- Commission percent applied to net sale (excluding tax). Admin can edit
  -- per affiliate, overriding the global default in partner_settings.
  commission_percent       numeric(5,2) NULL
                           CHECK (commission_percent IS NULL OR
                                  (commission_percent >= 0 AND commission_percent <= 100)),

  -- Attribution window, in days, from click to purchase. Spec: 30.
  attribution_window_days  integer      NOT NULL DEFAULT 30
                           CHECK (attribution_window_days > 0 AND attribution_window_days <= 365),

  -- Lifecycle: pending → active → suspended. Pending affiliates can generate
  -- links but no commission accrues until `active`. Matches the admin
  -- "approvals" requirement.
  status                   text         NOT NULL DEFAULT 'pending'
                           CHECK (status IN ('pending','active','suspended','closed')),

  -- Payout bookkeeping aggregate cache (the authoritative numbers are
  -- recomputed from conversions/payouts; these are for fast dashboard reads).
  payouts_owed_minor       integer      NOT NULL DEFAULT 0,
  total_paid_minor         integer      NOT NULL DEFAULT 0,
  payout_currency          text         NOT NULL DEFAULT 'SGD',

  created_at               timestamptz  NOT NULL DEFAULT now(),
  updated_at               timestamptz  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS affiliate_accounts_public_code_uq
  ON affiliate_accounts (public_code);
CREATE UNIQUE INDEX IF NOT EXISTS affiliate_accounts_email_uq
  ON affiliate_accounts (lower(email));
CREATE INDEX IF NOT EXISTS affiliate_accounts_user_idx
  ON affiliate_accounts (user_id);
CREATE INDEX IF NOT EXISTS affiliate_accounts_status_idx
  ON affiliate_accounts (status);

-- One row per affiliate link click. Attribution resolution at checkout reads
-- the most recent click for (visitor_token, affiliate) within the window.
-- `visitor_token` is the anonymous browser token the SPA sets (no PII); it
-- is what the 30-day cookie value is keyed off.
CREATE TABLE IF NOT EXISTS affiliate_clicks (
  id               bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  affiliate_id     integer      NOT NULL REFERENCES affiliate_accounts(id) ON DELETE CASCADE,

  visitor_token    text         NOT NULL,
  public_code      text         NOT NULL,

  -- Where the visitor landed (path + query) and where they came from.
  target_path      text         NULL,
  referrer         text         NULL,
  user_agent       text         NULL,
  ip_hash          text         NULL,     -- never the raw IP

  -- Optional campaign tag for blogger analytics. Free text.
  campaign         text         NULL,

  clicked_at       timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS affiliate_clicks_affiliate_time_idx
  ON affiliate_clicks (affiliate_id, clicked_at DESC);
CREATE INDEX IF NOT EXISTS affiliate_clicks_visitor_idx
  ON affiliate_clicks (visitor_token, clicked_at DESC);
CREATE INDEX IF NOT EXISTS affiliate_clicks_code_idx
  ON affiliate_clicks (public_code);

-- One row per attributed sale. `order_id` is soft to orders.id. Unique on
-- (affiliate_id, order_id) so a duplicate Stripe webhook can't double-credit.
CREATE TABLE IF NOT EXISTS affiliate_conversions (
  id                 bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  affiliate_id       integer      NOT NULL REFERENCES affiliate_accounts(id) ON DELETE CASCADE,
  order_id           integer      NOT NULL,        -- soft FK to orders.id

  -- Attribution trace: the click that put the cookie down.
  click_id           bigint       NULL REFERENCES affiliate_clicks(id) ON DELETE SET NULL,
  visitor_token      text         NULL,

  -- Money in MINOR units so commissions don't drift on rounding. `currency`
  -- is the order currency.
  order_total_minor  integer      NOT NULL CHECK (order_total_minor >= 0),
  commission_percent numeric(5,2) NOT NULL
                     CHECK (commission_percent >= 0 AND commission_percent <= 100),
  commission_minor   integer      NOT NULL CHECK (commission_minor >= 0),
  currency           text         NOT NULL,

  -- Lifecycle: pending → approved → paid; or → voided if the order refunds.
  status             text         NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending','approved','paid','voided')),

  -- When the order was confirmed paid (Stripe webhook time). Used for
  -- payout batching.
  sale_at            timestamptz  NOT NULL DEFAULT now(),
  created_at         timestamptz  NOT NULL DEFAULT now(),
  updated_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS affiliate_conversions_order_uq
  ON affiliate_conversions (affiliate_id, order_id);
CREATE INDEX IF NOT EXISTS affiliate_conversions_status_idx
  ON affiliate_conversions (affiliate_id, status);
CREATE INDEX IF NOT EXISTS affiliate_conversions_sale_idx
  ON affiliate_conversions (sale_at DESC);

-- Batches of approved commissions paid out. One row per payout run per
-- affiliate. `amount_minor` is the sum of the included commissions.
-- `payout_reference` is free text ("PayNow ref", "Wise transfer id", etc.).
CREATE TABLE IF NOT EXISTS affiliate_payouts (
  id                 bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  affiliate_id       integer      NOT NULL REFERENCES affiliate_accounts(id) ON DELETE CASCADE,

  amount_minor       integer      NOT NULL CHECK (amount_minor > 0),
  currency           text         NOT NULL,

  -- Comma-separated conversion ids for the audit trail. A jsonb array would
  -- be cleaner but this keeps parity with the existing growth module which
  -- uses text tokens for references.
  conversion_ids     text         NOT NULL,

  payout_reference   text         NULL,
  status             text         NOT NULL DEFAULT 'paid'
                     CHECK (status IN ('scheduled','paid','failed','reversed')),

  paid_at            timestamptz  NOT NULL DEFAULT now(),
  created_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS affiliate_payouts_affiliate_idx
  ON affiliate_payouts (affiliate_id, paid_at DESC);

-- ===========================================================================
-- PARTNERS (physical venues with printable QR standees)
-- ===========================================================================

-- A partner = a hotel, spa, restaurant, etc. Each partner gets a printable
-- QR standee whose destination is /partner/<slug>. The landing page renders
-- in EN/ZH/VI based on `default_locale` or the visitor's browser.
CREATE TABLE IF NOT EXISTS partner_accounts (
  id                       integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- URL-friendly handle: /partner/<slug>.
  slug                     text         NOT NULL,

  display_name             text         NOT NULL,
  contact_email            text         NOT NULL,

  -- Free-text address / notes. Used only on the admin dashboard + standee
  -- PDF template.
  address                  text         NULL,
  notes                    text         NULL,

  -- Default language for the printed standee. The online landing page still
  -- respects the visitor's chosen locale; this affects only printed copy.
  default_locale           text         NOT NULL DEFAULT 'en'
                           CHECK (default_locale IN ('en','zh','vi')),

  -- Commission percent per sale attributed to this partner's QR.
  commission_percent       numeric(5,2) NULL
                           CHECK (commission_percent IS NULL OR
                                  (commission_percent >= 0 AND commission_percent <= 100)),

  attribution_window_days  integer      NOT NULL DEFAULT 30
                           CHECK (attribution_window_days > 0 AND attribution_window_days <= 365),

  -- Same lifecycle as affiliates for consistency in the admin approvals UI.
  status                   text         NOT NULL DEFAULT 'pending'
                           CHECK (status IN ('pending','active','suspended','closed')),

  payouts_owed_minor       integer      NOT NULL DEFAULT 0,
  total_paid_minor         integer      NOT NULL DEFAULT 0,
  payout_currency          text         NOT NULL DEFAULT 'SGD',

  created_at               timestamptz  NOT NULL DEFAULT now(),
  updated_at               timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS partner_accounts_slug_uq
  ON partner_accounts (slug);
CREATE UNIQUE INDEX IF NOT EXISTS partner_accounts_email_uq
  ON partner_accounts (lower(contact_email));
CREATE INDEX IF NOT EXISTS partner_accounts_status_idx
  ON partner_accounts (status);

-- One row per QR scan / landing-page load. `landing_locale` is what we
-- actually served (resolved from visitor preference, not the printed default).
CREATE TABLE IF NOT EXISTS partner_clicks (
  id               bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  partner_id       integer      NOT NULL REFERENCES partner_accounts(id) ON DELETE CASCADE,

  visitor_token    text         NOT NULL,
  slug             text         NOT NULL,
  landing_locale   text         NOT NULL DEFAULT 'en'
                   CHECK (landing_locale IN ('en','zh','vi')),

  target_path      text         NULL,
  referrer         text         NULL,
  user_agent       text         NULL,
  ip_hash          text         NULL,

  clicked_at       timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS partner_clicks_partner_time_idx
  ON partner_clicks (partner_id, clicked_at DESC);
CREATE INDEX IF NOT EXISTS partner_clicks_visitor_idx
  ON partner_clicks (visitor_token, clicked_at DESC);

-- One row per attributed sale. Same shape/behaviour as affiliate_conversions
-- so dashboards can share rendering. Kept separate so a strict constraint
-- change on one cannot silently affect the other.
CREATE TABLE IF NOT EXISTS partner_conversions (
  id                 bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  partner_id         integer      NOT NULL REFERENCES partner_accounts(id) ON DELETE CASCADE,
  order_id           integer      NOT NULL,        -- soft FK to orders.id

  click_id           bigint       NULL REFERENCES partner_clicks(id) ON DELETE SET NULL,
  visitor_token      text         NULL,

  order_total_minor  integer      NOT NULL CHECK (order_total_minor >= 0),
  commission_percent numeric(5,2) NOT NULL
                     CHECK (commission_percent >= 0 AND commission_percent <= 100),
  commission_minor   integer      NOT NULL CHECK (commission_minor >= 0),
  currency           text         NOT NULL,

  status             text         NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending','approved','paid','voided')),

  sale_at            timestamptz  NOT NULL DEFAULT now(),
  created_at         timestamptz  NOT NULL DEFAULT now(),
  updated_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS partner_conversions_order_uq
  ON partner_conversions (partner_id, order_id);
CREATE INDEX IF NOT EXISTS partner_conversions_status_idx
  ON partner_conversions (partner_id, status);
CREATE INDEX IF NOT EXISTS partner_conversions_sale_idx
  ON partner_conversions (sale_at DESC);

CREATE TABLE IF NOT EXISTS partner_payouts (
  id                 bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  partner_id         integer      NOT NULL REFERENCES partner_accounts(id) ON DELETE CASCADE,
  amount_minor       integer      NOT NULL CHECK (amount_minor > 0),
  currency           text         NOT NULL,
  conversion_ids     text         NOT NULL,
  payout_reference   text         NULL,
  status             text         NOT NULL DEFAULT 'paid'
                     CHECK (status IN ('scheduled','paid','failed','reversed')),
  paid_at            timestamptz  NOT NULL DEFAULT now(),
  created_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS partner_payouts_partner_idx
  ON partner_payouts (partner_id, paid_at DESC);

-- ===========================================================================
-- B2B AGENTS
-- ===========================================================================

-- Applications are kept separate from the account so an application is
-- auditable even if it's rejected. `id_passport_ref` is a note field where
-- admin can record the verified doc reference (never the doc itself).
CREATE TABLE IF NOT EXISTS b2b_agent_applications (
  id                integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  company_name      text         NOT NULL,
  contact_name      text         NOT NULL,
  contact_email     text         NOT NULL,
  contact_phone     text         NULL,
  country           text         NULL,
  website           text         NULL,

  -- Free-text: "we sell to tour groups in HCMC", etc.
  business_summary  text         NULL,

  -- Consents + eligibility flags set by the applicant.
  consents          jsonb        NOT NULL DEFAULT '{}'::jsonb,

  status            text         NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','approved','rejected','withdrawn')),

  -- Reviewer bookkeeping.
  reviewed_by_user_id integer    NULL,
  reviewed_at       timestamptz  NULL,
  review_note       text         NULL,

  created_at        timestamptz  NOT NULL DEFAULT now(),
  updated_at        timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS b2b_applications_status_idx
  ON b2b_agent_applications (status, created_at DESC);
CREATE INDEX IF NOT EXISTS b2b_applications_email_idx
  ON b2b_agent_applications (lower(contact_email));

-- An approved agent. `tier` selects the row in `b2b_tier_pricing` used for
-- wholesale/resale pricing and available bulk-order limits.
CREATE TABLE IF NOT EXISTS b2b_agents (
  id                 integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  public_code        text         NOT NULL,

  -- Soft reference back to the application that approved them.
  application_id     integer      NULL REFERENCES b2b_agent_applications(id) ON DELETE SET NULL,

  company_name       text         NOT NULL,
  contact_email      text         NOT NULL,

  -- Tier: bronze / silver / gold. Admin can override pricing per-agent via
  -- the column below; otherwise pricing comes from b2b_tier_pricing.
  tier               text         NOT NULL DEFAULT 'bronze'
                     CHECK (tier IN ('bronze','silver','gold')),

  -- Optional override of the tier's markup (percent). NULL = use the tier.
  commission_or_markup_percent numeric(5,2) NULL
                     CHECK (commission_or_markup_percent IS NULL OR
                            (commission_or_markup_percent >= 0 AND commission_or_markup_percent <= 1000)),

  -- Bulk-order guardrail: how many eSIMs a single order can contain.
  max_bulk_quantity  integer      NOT NULL DEFAULT 50
                     CHECK (max_bulk_quantity > 0),

  -- If true, agent can purchase eSIMs on behalf of named clients; the client
  -- email is captured on the order rather than the agent's.
  can_send_to_clients boolean    NOT NULL DEFAULT true,

  status             text         NOT NULL DEFAULT 'active'
                     CHECK (status IN ('active','suspended','closed')),

  -- Soft FK back to a user account for the agent's primary login.
  user_id            integer      NULL,

  created_at         timestamptz  NOT NULL DEFAULT now(),
  updated_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS b2b_agents_public_code_uq
  ON b2b_agents (public_code);
CREATE UNIQUE INDEX IF NOT EXISTS b2b_agents_email_uq
  ON b2b_agents (lower(contact_email));
CREATE INDEX IF NOT EXISTS b2b_agents_tier_idx
  ON b2b_agents (tier, status);
CREATE INDEX IF NOT EXISTS b2b_agents_user_idx
  ON b2b_agents (user_id);

-- Per-tier pricing knobs, editable from the admin settings screen.
-- `markup_percent_above_retail` is how much ABOVE our normal retail the agent
-- pays (agents generally pay less than retail, so the value will usually be
-- negative; the CHECK allows 0..1000 either way as long as it's representable
-- as NUMERIC(6,2)). Separating "floor" from "markup" keeps the pricing rule
-- explicit.
CREATE TABLE IF NOT EXISTS b2b_tier_pricing (
  tier                       text         PRIMARY KEY
                             CHECK (tier IN ('bronze','silver','gold')),
  discount_percent_off_retail numeric(5,2) NOT NULL DEFAULT 0
                             CHECK (discount_percent_off_retail >= 0 AND
                                    discount_percent_off_retail <= 100),
  minimum_order_quantity     integer      NOT NULL DEFAULT 1
                             CHECK (minimum_order_quantity > 0),
  max_bulk_quantity          integer      NOT NULL DEFAULT 50
                             CHECK (max_bulk_quantity > 0),
  notes                      text         NULL,
  updated_at                 timestamptz  NOT NULL DEFAULT now()
);

-- Seed the three tier rows with sensible but conservative defaults. Admin
-- edits in the dashboard. `ON CONFLICT DO NOTHING` so re-running the
-- migration never overwrites an admin's customised values.
INSERT INTO b2b_tier_pricing (tier, discount_percent_off_retail, minimum_order_quantity, max_bulk_quantity, notes)
VALUES
  ('bronze', 10.00, 10,  50,  'Entry tier — 10% off retail, bulk from 10 units'),
  ('silver', 15.00, 25, 200,  'Established agent — 15% off retail, bulk from 25 units'),
  ('gold',   20.00, 50, 1000, 'Top tier — 20% off retail, bulk from 50 units')
ON CONFLICT (tier) DO NOTHING;

-- ===========================================================================
-- CORPORATE ACCOUNTS
-- ===========================================================================

-- A corporate account belongs to a company, not a single user. `owner_user_id`
-- is the company admin who can invite members and buy eSIMs on the company's
-- behalf.
CREATE TABLE IF NOT EXISTS corporate_accounts (
  id                 integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  public_code        text         NOT NULL,
  company_name       text         NOT NULL,

  billing_email      text         NOT NULL,
  billing_address    text         NULL,
  billing_currency   text         NOT NULL DEFAULT 'SGD',

  -- Invoicing cadence, stored as a token the invoice job understands.
  invoice_cycle      text         NOT NULL DEFAULT 'monthly'
                     CHECK (invoice_cycle IN ('monthly','quarterly','annual')),

  -- Net terms in days (invoice due date = issued_at + net_terms_days).
  net_terms_days     integer      NOT NULL DEFAULT 30
                     CHECK (net_terms_days >= 0 AND net_terms_days <= 180),

  -- Optional per-company discount off retail (e.g. negotiated rate).
  discount_percent_off_retail numeric(5,2) NULL
                     CHECK (discount_percent_off_retail IS NULL OR
                            (discount_percent_off_retail >= 0 AND
                             discount_percent_off_retail <= 100)),

  -- The user who can invite members. Soft FK to users.id.
  owner_user_id      integer      NOT NULL,

  status             text         NOT NULL DEFAULT 'active'
                     CHECK (status IN ('pending','active','suspended','closed')),

  created_at         timestamptz  NOT NULL DEFAULT now(),
  updated_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS corporate_accounts_public_code_uq
  ON corporate_accounts (public_code);
CREATE INDEX IF NOT EXISTS corporate_accounts_owner_idx
  ON corporate_accounts (owner_user_id);
CREATE INDEX IF NOT EXISTS corporate_accounts_billing_email_idx
  ON corporate_accounts (lower(billing_email));

-- A member of a corporate account. Belongs to exactly one user (unique FK);
-- user's role inside the company is `role`.
CREATE TABLE IF NOT EXISTS corporate_members (
  id                 integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  corporate_id       integer      NOT NULL REFERENCES corporate_accounts(id) ON DELETE CASCADE,
  user_id            integer      NOT NULL,        -- soft FK to users.id
  email              text         NOT NULL,
  display_name       text         NULL,
  role               text         NOT NULL DEFAULT 'staff'
                     CHECK (role IN ('admin','manager','staff')),
  status             text         NOT NULL DEFAULT 'active'
                     CHECK (status IN ('invited','active','suspended','removed')),
  invited_by_user_id integer      NULL,
  invited_at         timestamptz  NULL,
  joined_at          timestamptz  NULL,
  created_at         timestamptz  NOT NULL DEFAULT now(),
  updated_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS corporate_members_corp_user_uq
  ON corporate_members (corporate_id, user_id);
CREATE INDEX IF NOT EXISTS corporate_members_user_idx
  ON corporate_members (user_id);

-- An eSIM assigned to a corporate member. `esim_id` is a soft FK to
-- esims.id (see 0011_trips.sql for the same soft-join convention).
--
-- `order_id` records the corporate order that bought the eSIM so monthly
-- invoicing can roll the batch into a summary. `unassigned_at` is set when
-- the admin/staff member releases the eSIM after a trip (or when it's
-- replaced); the row is kept for audit.
CREATE TABLE IF NOT EXISTS corporate_assignments (
  id                 integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  corporate_id       integer      NOT NULL REFERENCES corporate_accounts(id) ON DELETE CASCADE,
  member_id          integer      NOT NULL REFERENCES corporate_members(id) ON DELETE CASCADE,
  esim_id            integer      NOT NULL,        -- soft FK to esims.id
  order_id           integer      NULL,            -- soft FK to orders.id

  -- Purchased price for invoicing.
  retail_price_minor integer      NOT NULL CHECK (retail_price_minor >= 0),
  currency           text         NOT NULL,

  assigned_by_user_id integer     NULL,
  assigned_at        timestamptz  NOT NULL DEFAULT now(),
  unassigned_at      timestamptz  NULL,
  notes              text         NULL,

  created_at         timestamptz  NOT NULL DEFAULT now(),
  updated_at         timestamptz  NOT NULL DEFAULT now()
);
-- One live assignment per eSIM. Partial index so re-assign after release is
-- permitted (a NEW row is created; the old one keeps `unassigned_at`).
CREATE UNIQUE INDEX IF NOT EXISTS corporate_assignments_live_uq
  ON corporate_assignments (esim_id)
  WHERE unassigned_at IS NULL;
CREATE INDEX IF NOT EXISTS corporate_assignments_corp_idx
  ON corporate_assignments (corporate_id, assigned_at DESC);
CREATE INDEX IF NOT EXISTS corporate_assignments_member_idx
  ON corporate_assignments (member_id, assigned_at DESC);

-- Monthly (or quarterly/annual) invoice summaries. The invoice references a
-- date range; the total is recomputed from corporate_assignments + any line
-- items the admin adds manually.
CREATE TABLE IF NOT EXISTS corporate_invoices (
  id                 integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  corporate_id       integer      NOT NULL REFERENCES corporate_accounts(id) ON DELETE CASCADE,
  public_code        text         NOT NULL,

  period_start       date         NOT NULL,
  period_end         date         NOT NULL,

  -- Stored at generation time for audit. Regeneration creates a NEW row.
  subtotal_minor     integer      NOT NULL CHECK (subtotal_minor >= 0),
  tax_minor          integer      NOT NULL DEFAULT 0 CHECK (tax_minor >= 0),
  total_minor        integer      NOT NULL CHECK (total_minor >= 0),
  currency           text         NOT NULL,

  -- Invoice lines as JSONB (this is a summary doc; the source rows are in
  -- corporate_assignments). Kept as JSONB so the invoice PDF can be
  -- regenerated without re-querying the assignment table.
  lines              jsonb        NOT NULL DEFAULT '[]'::jsonb,

  status             text         NOT NULL DEFAULT 'draft'
                     CHECK (status IN ('draft','issued','paid','void')),

  issued_at          timestamptz  NULL,
  due_at             timestamptz  NULL,
  paid_at            timestamptz  NULL,

  created_at         timestamptz  NOT NULL DEFAULT now(),
  updated_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS corporate_invoices_public_code_uq
  ON corporate_invoices (public_code);
CREATE INDEX IF NOT EXISTS corporate_invoices_corp_idx
  ON corporate_invoices (corporate_id, period_start DESC);
CREATE INDEX IF NOT EXISTS corporate_invoices_status_idx
  ON corporate_invoices (status);

-- ===========================================================================
-- SETTINGS (admin-editable knobs read by the partner/affiliate services)
-- ===========================================================================

-- The `settings` table already exists from 0001/0002. We seed only keys this
-- phase owns, and skip anything an earlier migration may already have
-- written (ON CONFLICT DO NOTHING).
