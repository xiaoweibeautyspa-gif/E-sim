--
-- Blog posts for the multilingual + blog milestone.
--
-- WHY THIS MIGRATION EXISTS
-- -------------------------
-- server/routes/blog.ts reads and writes `blog_posts`. The schema below is the
-- contract the route depends on and MUST stay in sync with it:
--
--   id, slug, status, locale, title, excerpt, body_md, cover_image_url,
--   author, tags, meta_title, meta_description, ai_generated,
--   ai_model, ai_cost_usd, published_at, created_at, updated_at
--
-- DESIGN NOTES
-- ------------
--  * `status` is a text column with a CHECK constraint ('draft' | 'published' |
--    'archived'). Only 'published' rows are visible on the public site, so an
--    AI-drafted post can never go live by accident — the admin must PATCH it to
--    'published' explicitly.
--  * `locale` is one of the storefront locales ('en' | 'zh' | 'vi'). A single
--    post belongs to one locale; translations are separate rows sharing a slug
--    family via `translation_group` so the reader can offer language links.
--  * Slugs are unique per locale (not globally) so e.g. "best-esim-japan" can
--    exist in both en and zh. The route builds URLs as /blog/<slug> for the
--    default locale and /<locale>/blog/<slug> for others, matching LocaleSwitcher.
--  * `ai_generated`, `ai_model`, `ai_cost_usd` record provenance + cost so the
--    admin dashboard can report AI spend (the AI helpers phase needs this).
--  * `body_md` is Markdown (not HTML): the reader renders it with a minimal,
--    escaping renderer, so a malicious AI draft can't inject raw HTML.
--
-- IDEMPOTENT: uses IF NOT EXISTS and additive ALTERs so re-running on a DB where
-- it has already been applied is harmless.

BEGIN;

CREATE TABLE IF NOT EXISTS blog_posts (
  id               integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- URL slug. Lowercase, hyphenated; enforced by the route, not a constraint,
  -- so an admin can fix a slug in place without a DB error.
  slug             varchar(160) NOT NULL,

  -- One of 'draft' | 'published' | 'archived'. The public reader filters to
  -- 'published' only.
  status           varchar(16) NOT NULL DEFAULT 'draft',

  -- Storefront locale. 'en' posts are served at /blog/<slug>, others at
  -- /<locale>/blog/<slug>.
  locale           varchar(8) NOT NULL DEFAULT 'en',

  title            varchar(300) NOT NULL,
  excerpt          text NOT NULL DEFAULT '',
  body_md          text NOT NULL DEFAULT '',

  -- Optional absolute or root-relative image URL. Root-relative is preferred so
  -- OG image generation can prepend the public base URL.
  cover_image_url  text,

  author           varchar(120) NOT NULL DEFAULT '',

  -- JSON array of lowercase tag strings, e.g. ["japan","esim","guide"].
  tags             jsonb NOT NULL DEFAULT '[]'::jsonb,

  meta_title       varchar(300),
  meta_description varchar(400),

  -- Provenance for AI-drafted posts. `ai_generated = FALSE` for human-authored
  -- posts. `ai_model` matches the provider/model string, e.g. "openai:gpt-4o".
  ai_generated     boolean NOT NULL DEFAULT FALSE,
  ai_model         varchar(80),
  ai_cost_usd      numeric(12, 6) NOT NULL DEFAULT 0,

  published_at     timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),

  -- Translation grouping: rows that are the "same article" across locales share
  -- this value so the reader can show language links. NULL means no link.
  translation_group varchar(160),

  CONSTRAINT blog_posts_status_ck
    CHECK (status IN ('draft', 'published', 'archived'))
);

-- One slug per locale. Two locales can share a slug string.
CREATE UNIQUE INDEX IF NOT EXISTS blog_posts_slug_locale_uq
  ON blog_posts (locale, slug);

-- Public listing + sitemap queries: published only, newest first.
CREATE INDEX IF NOT EXISTS blog_posts_published_idx
  ON blog_posts (published_at DESC)
  WHERE status = 'published';

-- Admin queue: drafts awaiting review.
CREATE INDEX IF NOT EXISTS blog_posts_drafts_idx
  ON blog_posts (created_at DESC)
  WHERE status = 'draft';

-- Localised listings.
CREATE INDEX IF NOT EXISTS blog_posts_locale_status_idx
  ON blog_posts (locale, status);

-- Translation grouping lookup.
CREATE INDEX IF NOT EXISTS blog_posts_translation_group_idx
  ON blog_posts (translation_group)
  WHERE translation_group IS NOT NULL;

-- Keep updated_at honest without every route remembering to set it.
CREATE OR REPLACE FUNCTION blog_posts_touch_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS blog_posts_touch_updated_at ON blog_posts;
CREATE TRIGGER blog_posts_touch_updated_at
  BEFORE UPDATE ON blog_posts
  FOR EACH ROW
  EXECUTE FUNCTION blog_posts_touch_updated_at();

COMMIT;
