-- Saved trips for the AI trip planner.
--
-- Why this migration is in the persistence batch (nominally queued):
-- `/api/trips` cannot function without the table, and inventing a fake
-- in-memory store for shareable links would be a lie. Applies cleanly on a
-- database where 0001_init.sql … 0010_affiliate_ids.sql have already run.
--
-- Notes:
--  - `public_id` is the /trip/[id] token. Base32 (unambiguous alphabet),
--    12 chars → ~60 bits of entropy. Unique.
--  - `departure_date` is date-text (YYYY-MM-DD) rather than a timestamp so
--    timezone is not silently reinterpreted by the reminder job; the job
--    compares against the *user's local* date.
--  - `esim_id` is intentionally FK-less here: `esims.id` semantics are owned
--    by 0005/0007, and we don't want to break this migration if those change.
--    We do add a comment so ops know the intended join key.
--  - Users are not FK'd for the same reason. The app resolves ownership at
--    read time (see server/routes/trips.ts).

CREATE TABLE IF NOT EXISTS trips (
    id              integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    public_id       text         NOT NULL,
    user_id         integer      NULL,
    owner_email     text         NOT NULL,
    countries       jsonb        NOT NULL,
    start_date      text         NOT NULL,
    end_date        text         NOT NULL,
    departure_date  text         NOT NULL,
    style           text         NOT NULL,
    language        text         NOT NULL,
    plan_text       text         NOT NULL,
    meta            jsonb        NOT NULL DEFAULT '{}'::jsonb,
    esim_id         integer      NULL,
    is_public       boolean      NOT NULL DEFAULT true,
    reminder_sent_at timestamptz NULL,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS trips_public_id_uq
    ON trips (public_id);

CREATE INDEX IF NOT EXISTS trips_user_idx
    ON trips (user_id);

CREATE INDEX IF NOT EXISTS trips_departure_idx
    ON trips (departure_date);

-- Row comment: esim_id joins esims.id when a "Stay connected" purchase is
-- attached. Kept soft (no FK) because esims.id is owned by 0005/0007.
COMMENT ON COLUMN trips.esim_id IS
    'Soft join to esims.id. The offline pack reads the QR/LPA via this id when present.';
COMMENT ON COLUMN trips.public_id IS
    'Share token for /trip/[publicId]. Unguessable, not a numeric id.';
